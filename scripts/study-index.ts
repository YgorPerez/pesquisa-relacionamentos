// The README's "Índice de estudos", generated from the fact sheets (#98).
// Acervo PRs did not touch README.md, so a hand-written index always lagged
// behind `studies/`. Each line comes from the fact sheet itself, read by
// `packages/content`'s loader:
//
//   [<authors> <year>](studies/<slug>.md): <short finding> · <status> · <strength>
//
// The authors, year and short finding come from the body's title
// ("# Autor (ano): tema"), the emoji from `status` and the word from
// `strength`. The frontmatter has no theme, so the lines are grouped by where
// the data comes from (`countries`), the closest grouping it can derive.
//
//   node scripts/study-index.ts          rewrites the section in README.md
//   node scripts/study-index.ts --check  exits 1 when README.md is stale
//
// `pnpm check` runs the second one.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import {
  formatProblems,
  loadLibrary,
  type FactSheet,
  type Strength,
  type VerificationStatus,
} from '../packages/content/src/index.ts'

export const START =
  '<!-- study-index: generated by `node scripts/study-index.ts`, do not edit by hand -->'
export const END = '<!-- /study-index -->'

const STATUS_EMOJI: Record<VerificationStatus, string> = {
  verified: '✅',
  partial: '🟡',
  unverified: '⬜',
}

/** As the site writes it (`frontend/src/ui/badges.copy.ts`). */
const STRENGTH_WORD: Record<Strength, string> = {
  strong: 'forte',
  moderate: 'moderada',
  weak: 'fraca',
}

const BRAZIL = 'Brasil'

/** The groups in README order, each with the fact sheets it takes. */
const GROUPS: ReadonlyArray<{
  readonly heading: string
  readonly takes: (countries: ReadonlyArray<string>) => boolean
}> = [
  {
    heading: 'Com dados do Brasil',
    takes: (countries) => countries.includes(BRAZIL),
  },
  {
    heading: 'Outros países',
    takes: (countries) => countries.length > 0 && !countries.includes(BRAZIL),
  },
  {
    heading: 'Sem país na Ficha (meta-análises e bases de vários países)',
    takes: (countries) => countries.length === 0,
  },
]

type Entry = Pick<
  FactSheet,
  'slug' | 'title' | 'status' | 'strength' | 'countries'
>

/** "Aron et al. (1997): as perguntas" → ["Aron et al. 1997", "as perguntas"].
 * A title without a year or without a theme keeps what it has. */
export function splitTitle(title: string): { label: string; finding: string } {
  const colon = title.indexOf(': ')
  const head = colon === -1 ? title : title.slice(0, colon)
  const finding = colon === -1 ? '' : title.slice(colon + 2).trim()
  const label = head.replace(/\s*\(([^)]*)\)\s*$/, ' $1').trim()
  return { label, finding }
}

export function line(entry: Entry): string {
  const { label, finding } = splitTitle(entry.title)
  const link = `[${label}](studies/${entry.slug}.md)`
  const tail = `${STATUS_EMOJI[entry.status]} · ${STRENGTH_WORD[entry.strength]}`
  return finding ? `- ${link}: ${finding} · ${tail}` : `- ${link} · ${tail}`
}

/** The markdown between the markers: one `###` per group that has fact sheets,
 * the lines in slug order. */
export function studyIndex(entries: ReadonlyArray<Entry>): string {
  const sorted = [...entries].sort((a, b) => a.slug.localeCompare(b.slug))
  return GROUPS.flatMap(({ heading, takes }) => {
    const lines = sorted.filter((e) => takes(e.countries)).map(line)
    return lines.length === 0 ? [] : [`### ${heading}\n\n${lines.join('\n')}`]
  }).join('\n\n')
}

/** README with the text between the markers replaced, or `null` when a marker
 * is missing. */
export function withIndex(readme: string, index: string): string | null {
  const start = readme.indexOf(START)
  const end = readme.indexOf(END)
  if (start === -1 || end === -1 || end < start) return null
  return `${readme.slice(0, start + START.length)}\n\n${index}\n\n${readme.slice(end)}`
}

const REGENERATE = 'node scripts/study-index.ts'

export function main(
  argv: ReadonlyArray<string>,
  { root, write }: { root: string; write: (line: string) => void },
): number {
  const check = argv.includes('--check')
  const loaded = loadLibrary(root)
  if (!loaded.ok) {
    write('study-index: the library does not load, fix these first:')
    write(formatProblems(loaded.errors))
    return 1
  }
  const file = join(root, 'README.md')
  const readme = readFileSync(file, 'utf8')
  const next = withIndex(readme, studyIndex(loaded.library.factSheets))
  if (next === null) {
    write(
      `study-index: README.md lacks the markers ${START} and ${END} around the index.`,
    )
    return 1
  }
  if (next === readme) return 0
  if (check) {
    write(
      `study-index: the "Índice de estudos" in README.md does not match studies/. Run \`${REGENERATE}\` and commit README.md.`,
    )
    return 1
  }
  writeFileSync(file, next)
  write('study-index: README.md updated.')
  return 0
}

if (import.meta.main) {
  process.exitCode = main(process.argv.slice(2), {
    root: resolve(import.meta.dirname, '..'),
    write: (l) => console.log(l),
  })
}
